#!/usr/bin/env node
// Extract the authored emissive strip, not geometry or a rendered screenshot.
// Usage: node scripts/extract-black-hole-palette.mjs /path/to/black_hole.glb
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const input = process.argv[2];
if (!input) throw new Error('Supply the original Nestaeric Black Hole GLB path');
const glb = await readFile(input);
if (glb.readUInt32LE(0) !== 0x46546c67) throw new Error('Expected a GLB');
const jsonLength = glb.readUInt32LE(12);
const model = JSON.parse(glb.subarray(20, 20 + jsonLength));
const material = model.materials.find(m => m.name === 'black_hole_light1');
const image = model.images[model.textures[material.emissiveTexture.index].source];
const view = model.bufferViews[image.bufferView];
const binaryStart = 28 + jsonLength;
const png = glb.subarray(binaryStart + view.byteOffset,
  binaryStart + view.byteOffset + view.byteLength);
const { data, info } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const column = Math.floor(info.width / 2);
const rgba = Array.from({ length: info.height }, (_, y) =>
  [...data.subarray((y * info.width + column) * 4, (y * info.width + column + 1) * 4)]).flat();
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const source = {
  ...model.asset.extras,
  glbSha256: hash(glb),
  emissivePngSha256: hash(png),
  modification: 'Central vertical column of black_hole_light1 emissive map, transposed to a 512x1 radial colour lookup; geometry and animation are original Cochonnet Villa shaders.'
};
const output = new URL('../src/villa-map/observatory-disc-palette-data.js', import.meta.url);
await writeFile(output, `// Generated by scripts/extract-black-hole-palette.mjs.\n// Texture derivative: NestaEric, CC BY 4.0. See public/data/observatory-disc-palette-LICENSE.txt.\nexport const DISC_PALETTE_SOURCE = ${JSON.stringify(source, null, 2)};\nexport const DISC_PALETTE_RGBA = new Uint8Array([\n${Array.from({ length: info.height / 8 }, (_, row) => '  ' + rgba.slice(row * 32, (row + 1) * 32).join(',')).join(',\n')}\n]);\n`);
console.log(`Extracted ${info.height} RGBA samples (${rgba.length} bytes)`);
